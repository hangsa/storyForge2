# Must match v1.x InitRequest in backend/api/creative_diverge.py.
_MAX_PROMPT_LEN = 1700

_PROMPTS_DIR = Path(__file__).parent.parent / "prompts"
_NEXT_STEP_PROMPT_PATH = _PROMPTS_DIR / "canvas_v2_next_step.yaml"
_logger = logging.getLogger(__name__)


def _load_next_step_prompt() -> dict:
    """Load next-step prompt template from YAML. Cached after first call."""
    if not hasattr(_load_next_step_prompt, "_cache"):
        with open(_NEXT_STEP_PROMPT_PATH, encoding="utf-8") as f:
            _load_next_step_prompt._cache = yaml.safe_load(f)
    return _load_next_step_prompt._cache


async def _call_llm_with_retry(llm_call, context, max_attempts=2):
    """Call LLM with JSON retry (spec §6.5).

    Retries ONCE on JSON parse failure. The retry sets
    ``context["retry_hint"]`` to "Please return valid JSON only"; the
    caller is responsible for reading this key and prepending it to the
    prompt sent to the LLM on the second attempt. Without that step,
    retries will fail the same way and the helper will raise after
    exhaustion.

    Retry interval is 0 (immediate). Raises RuntimeError after exhaustion.
    """
    last_error = None
    for attempt in range(max_attempts):
        try:
            raw = await llm_call(context)
            return json.loads(raw)
        except (json.JSONDecodeError, ValueError) as exc:
            last_error = exc
            _logger.warning("LLM JSON parse failed on attempt %d: %s", attempt + 1, exc)
            if attempt + 1 < max_attempts:
                context = {**context, "retry_hint": "Please return valid JSON only"}
    raise RuntimeError(
        f"LLM 返回了无效 JSON ({max_attempts} 次): {last_error or 'no attempts'}"
    )


def _validate_for_commit(canvas: dict) -> None:
    """Validate canvas is ready to commit.

    Checks (spec §4.4):
      1. ≥ 2 steps COMPLETED
      2. No STALE steps
      3. Step 5 specifically COMPLETED (v2.0 MVP — no early-finalize)

    Note: this function does NOT check `final_concept` — final_concept is
    generated by step 2 of the commit handler AFTER step 1 invokes this
    function. Validation of the generated final_concept happens in step 3
    of the commit handler.
    """
    path = canvas.get("creative_path", [])
    completed = [p for p in path if p.get("state") == "completed"]
    if len(completed) < 2:
        raise HTTPException(
            status_code=422,
            detail={
                "error": True,
                "code": "INVALID_PATH",
                "message": "至少需要 2 步 COMPLETED",
                "detail": {},
            },
        )
    stale = [p for p in path if p.get("state") == "stale"]
    if stale:
        raise HTTPException(
            status_code=422,
            detail={
                "error": True,
                "code": "INVALID_PATH",
                "message": f"{len(stale)} 个 STALE 步骤需要处理",
                "detail": {},
            },
        )
    step5 = next((p for p in path if p.get("step") == 5), None)
    if not step5 or step5.get("state") != "completed":
        raise HTTPException(
            status_code=422,
            detail={
                "error": True,
                "code": "INVALID_PATH",
                "message": "Step 5 必须走完(v2.0 MVP 不支持早收束)",
                "detail": {},
            },
        )


# --- Pydantic models ---


class InitRequest(BaseModel):
    prompt: str = Field(..., min_length=1, max_length=_MAX_PROMPT_LEN)
    genre_primary: str = Field(..., min_length=1)
    genre_secondary: Optional[str] = None
    target_reader: Optional[str] = None
    reference_works: Optional[List[str]] = None
    forbidden_directions: Optional[List[str]] = None
    quick_mode: bool = False


class NextStepRequest(BaseModel):
    current_step: int = Field(..., ge=1, le=5)


class SelectRequest(BaseModel):
    step: int = Field(..., ge=1, le=5)
    option_id: str = Field(..., min_length=1)


# --- /init ---


def _empty_canvas_v4() -> dict:
    """Construct an empty v4 canvas skeleton (PRD §22).

    Used by:
      - POST /init (with root_idea + raw_intent populated by caller)
      - DELETE /state (resets session; root_idea + raw_intent preserved
        by copying them in from the existing canvas before write)

    Timestamps (`computed_at`, `created_at`, `last_modified_at`) reflect
    the time of construction; callers may overwrite `last_modified_at`
    on reset.
    """
    now = datetime.now(timezone.utc).isoformat()
    return {
        "schema_version": 4,
        "session_id": str(uuid.uuid4()),
        "root_idea": {
            "prompt": "",
            "genre": "",
            "premise": "",
            "extracted": {
                "genre": "",
                "core_elements": [],
                "potential_conflict": "",
            },
        },
        "raw_intent": {
            "prompt": "",
            "genre_primary": "",
            "genre_secondary": None,
            "target_reader": None,
            "reference_works": [],
            "forbidden_directions": [],
            "quick_mode": False,
            "trope_tags": [],
        },
        "creative_session": {
            "current_step": 1,
            "max_steps": 5,
            "status": "active",
        },
        "creative_path": [],
        "current_concept": {
            "premise": "",
            "core_conflict": "",
            "characters": [],
            "world_rules": [],
            "tropes": [],
            "themes": [],
            "novelty": 0.0,
        },
        "final_concept": None,
        "committed": False,
        "committed_at": None,
        "committed_concept_ref": "concept_and_dna.json",
        "scores": {
            "novelty": 0.0,
            "conflict": 0.0,
            "story_potential": 0.0,
            "uniqueness": 0.0,
            "computed_at": now,
        },
        "session_metadata": {
            "created_at": now,
            "last_modified_at": now,
            "elapsed_seconds": 0,
            "operation_count": 0,
        },
    }


@router.post("/session/init")
async def init_canvas_v2(project_id: str, body: InitRequest):
    """Initialize v2 canvas with raw_intent + root_idea dual-write.

    Writes PRD §22 enriched schema: root_idea (with extracted.genre +
    extracted.potential_conflict), creative_session, current_concept, top-level
    scores (with computed_at timestamp), session_metadata.elapsed_seconds, and
    committed_concept_ref (PRD §23.4).
    """
    _ensure_project(project_id)

    canvas = _empty_canvas_v4()
    canvas["root_idea"] = {
        "prompt": body.prompt,
        "genre": body.genre_primary,
        "premise": body.prompt,
        "extracted": {
            "genre": body.genre_primary,
            "core_elements": [],
            "potential_conflict": "",
        },
    }
    canvas["raw_intent"] = {
        "prompt": body.prompt,
        "genre_primary": body.genre_primary,
        "genre_secondary": body.genre_secondary,
        "target_reader": body.target_reader,
        "reference_works": body.reference_works or [],
        "forbidden_directions": body.forbidden_directions or [],
        "quick_mode": body.quick_mode,
        "trope_tags": [],
    }
    # Pre-populate creative_path with the step 1 entry so the UI can show
    # an "available" step 1 card immediately on init (matches PRD §22:
    # creative_path starts as a list with one available entry).
    now = canvas["scores"]["computed_at"]
    canvas["creative_path"] = [{
        "step": 1,
        "operation": None,
        "operation_reason": None,
        "options": [],
        "selected_option_id": None,
        "created_at": now,
        "selected_at": None,
        "regenerated_count": 0,
        "state": "available",
    }]
    canvas["current_concept"]["premise"] = body.prompt

    etag = _compute_etag(canvas)
    canvas["_etag"] = etag
    _write_canvas(project_id, canvas)

    return {"ok": True, "session_id": canvas["session_id"], "etag": etag}


